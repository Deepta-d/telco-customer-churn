-- Telco Customer Churn — MySQL schema (Phase 2)
-- Run: mysql -u root -p < sql/schema.sql

DROP DATABASE IF EXISTS telco_churn;
CREATE DATABASE telco_churn
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE telco_churn;

DROP TABLE IF EXISTS telco_customers;

CREATE TABLE telco_customers (
    customer_id           VARCHAR(20)   NOT NULL PRIMARY KEY,
    customer_count        INT           NOT NULL,
    country               VARCHAR(50)   NOT NULL,
    state                 VARCHAR(50)   NOT NULL,
    city                  VARCHAR(100)  NOT NULL,
    zip_code              INT           NOT NULL,
    lat_long              VARCHAR(50)   NULL,
    latitude              DECIMAL(10, 6) NOT NULL,
    longitude             DECIMAL(10, 6) NOT NULL,
    gender                VARCHAR(10)   NOT NULL,
    senior_citizen        VARCHAR(5)    NOT NULL,
    partner               VARCHAR(5)    NOT NULL,
    dependents            VARCHAR(5)    NOT NULL,
    tenure_months         INT           NOT NULL,
    phone_service         VARCHAR(5)    NOT NULL,
    multiple_lines        VARCHAR(20)   NOT NULL,
    internet_service      VARCHAR(20)   NOT NULL,
    online_security       VARCHAR(20)   NOT NULL,
    online_backup         VARCHAR(20)   NOT NULL,
    device_protection     VARCHAR(20)   NOT NULL,
    tech_support          VARCHAR(20)   NOT NULL,
    streaming_tv          VARCHAR(25)   NOT NULL,
    streaming_movies      VARCHAR(25)   NOT NULL,
    contract              VARCHAR(20)   NOT NULL,
    plan_type             VARCHAR(20)   NOT NULL,
    paperless_billing     VARCHAR(5)    NOT NULL,
    payment_method        VARCHAR(40)   NOT NULL,
    monthly_charges       DECIMAL(10, 2) NOT NULL,
    total_charges         DECIMAL(10, 2) NOT NULL,
    churn_label           VARCHAR(5)    NOT NULL,
    churn_value           TINYINT       NOT NULL,
    churn_score           INT           NOT NULL,
    cltv                  INT           NOT NULL,
    churn_reason          VARCHAR(100)  NULL,
    tenure_group          VARCHAR(20)   NULL,
    avg_monthly_spend     DECIMAL(10, 2) NOT NULL,
    charge_drift          DECIMAL(10, 2) NOT NULL,
    cltv_per_month        DECIMAL(10, 2) NOT NULL,
    is_senior             TINYINT       NOT NULL,
    has_partner           TINYINT       NOT NULL,
    has_dependents        TINYINT       NOT NULL,
    household_size_proxy  TINYINT       NOT NULL,
    family_household      TINYINT       NOT NULL,
    contract_ordinal      TINYINT       NOT NULL,
    is_month_to_month     TINYINT       NOT NULL,
    is_paperless          TINYINT       NOT NULL,
    is_autopay            TINYINT       NOT NULL,
    is_electronic_check   TINYINT       NOT NULL,
    internet_fiber        TINYINT       NOT NULL,
    internet_dsl          TINYINT       NOT NULL,
    no_internet           TINYINT       NOT NULL,
    has_phone             TINYINT       NOT NULL,
    has_multiple_lines    TINYINT       NOT NULL,
    addon_services_count  TINYINT       NOT NULL,
    streaming_services_count TINYINT    NOT NULL,
    total_services_count  TINYINT       NOT NULL,
    has_streaming_bundle  TINYINT       NOT NULL,
    high_monthly_charge   TINYINT       NOT NULL,
    engagement_score      DECIMAL(6, 2) NOT NULL,
    risk_score            DECIMAL(6, 2) NOT NULL,
    risk_segment          VARCHAR(20)   NULL,
    reference_date        DATE          NOT NULL,
    join_date             DATE          NOT NULL,
    join_month            VARCHAR(7)    NOT NULL,
    churn_date            DATE          NULL,
    churn_month           VARCHAR(7)    NULL,
    is_high_value         TINYINT       NOT NULL,
    basic_cltv_calc       DECIMAL(12, 2) NOT NULL,
    INDEX idx_plan_type (plan_type),
    INDEX idx_churn_value (churn_value),
    INDEX idx_churn_month (churn_month),
    INDEX idx_join_month (join_month),
    INDEX idx_risk_score (risk_score),
    INDEX idx_is_high_value (is_high_value),
    INDEX idx_tenure_months (tenure_months)
) ENGINE=InnoDB;
